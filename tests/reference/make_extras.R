## Extra reference results (profile/confint, predict, glmer.nb, lmList, nlmer)
suppressMessages(library(lme4)); library(jsonlite)
out <- list()
fm1 <- lmer(Reaction ~ Days + (Days | Subject), sleepstudy)
fd  <- lmer(Yield ~ 1 | Batch, Dyestuff)
gm1 <- glmer(cbind(incidence, size - incidence) ~ period + (1 | herd), cbpp, binomial)
## predictions first: profiling modifies the fitted objects in place (reference classes)
nd <- data.frame(Days = c(0, 2.5, 10), Subject = factor(c("308", "335", "999")))
out$predict_sleep_newlevel <- unname(predict(fm1, nd, allow.new.levels = TRUE))
out$predict_sleep_reNA     <- unname(predict(fm1, nd, re.form = NA))
out$predict_cbpp_resp      <- unname(predict(gm1, type = "response"))
nd2 <- data.frame(period = factor(c("1","4"), levels = levels(cbpp$period)), herd = factor(c("1","15"), levels = levels(cbpp$herd)))
out$predict_cbpp_newdata   <- unname(predict(gm1, nd2, type = "response"))
ci <- function(x) list(rows = rownames(x), lower = unname(x[,1]), upper = unname(x[,2]))
out$confint_sleep_profile <- ci(confint(fm1, method = "profile"))
out$confint_sleep_wald    <- ci(confint(fm1, method = "Wald"))
out$confint_dyestuff_prof <- ci(confint(fd))
out$confint_cbpp_profile  <- ci(confint(gm1))
gnb <- glmer.nb(TICKS ~ YEAR + (1 | BROOD), grouseticks)
out$nb <- list(theta = getME(gnb, "glmer.nb.theta"), fixef = unname(fixef(gnb)),
               ftheta = unname(getME(gnb, "theta")), logLik = as.numeric(logLik(gnb)))
ll <- lmList(Reaction ~ Days | Subject, sleepstudy)
out$lmList <- list(coef = unname(as.matrix(coef(ll))), rows = rownames(coef(ll)), sigma = summary(ll)$RSE)
nm1 <- nlmer(circumference ~ SSlogis(age, Asym, xmid, scal) ~ Asym | Tree, Orange,
             start = c(Asym = 200, xmid = 725, scal = 350))
out$nlmer <- list(fixef = unname(fixef(nm1)), theta = unname(getME(nm1, "theta")),
                  sigma = sigma(nm1), logLik = as.numeric(logLik(nm1)))
an <- anova(lmer(Reaction ~ 1 + (Days | Subject), sleepstudy), fm1)
out$anova <- list(Chisq = an$Chisq[2], Df = an$Df[2], p = an[["Pr(>Chisq)"]][2], AIC = an$AIC)
d1 <- drop1(lmer(angle ~ recipe + temperature + (1 | recipe:replicate), cake), test = "Chisq")
out$drop1 <- list(rows = rownames(d1), npar = d1$npar, AIC = d1$AIC, LRT = d1$LRT, p = d1[["Pr(Chi)"]])
writeLines(toJSON(out, digits = NA, auto_unbox = TRUE), "extras.json")
cat("done\n")
